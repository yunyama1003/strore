CREATE TABLE IF NOT EXISTS items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    category VARCHAR(30) NOT NULL CHECK (category IN
        ('TOILETRIES', 'BATH', 'LAUNDRY', 'CLEANING', 'KITCHEN', 'PAPER', 'OTHER')),
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 0 AND 9999),
    minimum_quantity INTEGER NOT NULL CHECK (minimum_quantity BETWEEN 0 AND 9999),
    note VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
